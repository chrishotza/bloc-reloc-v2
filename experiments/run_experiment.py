"""Run the minimal two-variant BLOC-RELOC v2 experiment safely.

This runner reads trusted local graph pickles (generated by run_generation.py),
and writes NEW data into an untracked local results directory by default.
It does not reproduce the archived six-configuration Dynamics Observatory.
"""
from __future__ import annotations

import argparse
import csv
from pathlib import Path
import pickle
import time

from src.bloc_reloc_v2.core import BlocRelocV2

DEFAULT_GRAPH_DIR = Path("data/graphs")
DEFAULT_OUTPUT = Path("results/local/bloc_reloc_v2_results.csv")
VARIANTS = ("baseline", "affinity_modified")
FIELDS = ("graph", "variant", "edge_cut", "runtime", "nodes", "edges")


def parse_args(argv=None):
    parser = argparse.ArgumentParser(
        description="Minimal BLOC-RELOC v2 comparison using trusted local graph fixtures."
    )
    parser.add_argument(
        "--graph-dir", type=Path, default=DEFAULT_GRAPH_DIR,
        help="directory with locally generated, trusted .pkl NetworkX graphs"
    )
    parser.add_argument(
        "--output", type=Path, default=DEFAULT_OUTPUT,
        help="new CSV destination; default is untracked results/local/"
    )
    parser.add_argument(
        "--overwrite", action="store_true",
        help="explicitly permit replacing an existing output CSV"
    )
    parser.add_argument("--seed", type=int, default=42, help="algorithm seed (default: 42)")
    parser.add_argument(
        "--iterations", type=int, default=50,
        help="refinement iterations per graph/variant (default: 50)"
    )
    return parser.parse_args(argv)


def run(args) -> Path:
    if args.iterations < 1:
        raise SystemExit("--iterations must be >= 1")
    graph_dir = args.graph_dir
    if not graph_dir.is_dir():
        raise SystemExit(
            f"No input graph directory: {graph_dir}. "
            "First run: python -m experiments.run_generation"
        )
    graphs = sorted(graph_dir.glob("*.pkl"))
    if not graphs:
        raise SystemExit(
            f"No .pkl graphs in {graph_dir}. "
            "First run: python -m experiments.run_generation"
        )
    output = args.output
    if output.exists() and not args.overwrite:
        raise SystemExit(
            f"Refusing to overwrite existing results: {output}. "
            "Pass --output with a different path or explicitly use --overwrite."
        )
    if output.exists() and output.is_dir():
        raise SystemExit(f"CSV output path is a directory: {output}")

    rows = []
    for path in graphs:
        # WARNING: pickle can execute code; only load trusted locally generated graphs.
        with path.open("rb") as stream:
            graph = pickle.load(stream)

        for variant in VARIANTS:
            start = time.perf_counter()
            result = BlocRelocV2(
                graph, k=4, seed=args.seed, variant=variant
            ).refine(args.iterations)

            rows.append({
                "graph": path.name,
                "variant": variant,
                "edge_cut": result["edge_cut"],
                "runtime": time.perf_counter() - start,
                "nodes": graph.number_of_nodes(),
                "edges": graph.number_of_edges(),
            })
            print(path.name, variant, result["edge_cut"])

    output.parent.mkdir(parents=True, exist_ok=True)
    # Exclusive creation makes repeated runs refuse overwriting, even if the
    # destination appeared after the initial check.
    mode = "w" if args.overwrite else "x"
    with output.open(mode, newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=FIELDS)
        writer.writeheader()
        writer.writerows(rows)
    print(f"Saved {len(rows)} rows: {output}")
    return output


def main(argv=None):
    run(parse_args(argv))


if __name__ == "__main__":
    main()
